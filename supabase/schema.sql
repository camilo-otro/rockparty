-- Ranked song search (#82): every term must appear in the combined title+artist
-- text (cross-field); ranks exact title > prefix > exact artist > trigram sim >
-- alphabetical BEFORE limiting (fixes exact matches getting cut by the limit).
-- Called via supabase.rpc('search_songs', { q, lim }).
create or replace function public.search_songs(q text, lim int default 20)
returns setof public.song language sql stable set search_path = '' as $$
  with c as (select lower(trim(q)) as ql),
       terms as (select unnest(string_to_array((select ql from c), ' ')) as term)
  select s.*
  from public.song s, c
  where c.ql <> ''
    and not exists (
      select 1 from terms t
      where t.term <> ''
        and lower(coalesce(s.title, '') || ' ' || coalesce(s.artist, '')) not like '%' || t.term || '%'
    )
  order by
    (lower(s.title) = c.ql) desc,
    (lower(s.title) like c.ql || '%') desc,
    (lower(coalesce(s.artist, '')) = c.ql) desc,
    public.similarity(lower(coalesce(s.title, '') || ' ' || coalesce(s.artist, '')), c.ql) desc,  -- pg_trgm (public, search_path is '')
    s.title
  limit least(greatest(lim, 1), 50);
$$;

-- performance — a song slotted into a party's set list (drag-orderable).
-- party_set — a band's block as ONE orderable thing (#110).
-- A CONTAINER of performances, never a replacement for one: live_state is the
-- now-playing pointer, and applause / performance_user / started_at are all
-- per-song, so collapsing a band's ten songs into one row would destroy them.
-- A night is a sequence of sets; a set is a sequence of songs.
-- band_id NULL = an OPEN set: anyone may add, created and garbage-collected
-- implicitly by the triggers on performance. No unique (party_id, band_id) —
-- a headliner playing two sets with an open block between them is normal.
create table if not exists public.party_set (
  id         bigint generated by default as identity primary key,
  party_id   bigint not null references public.party (id) on delete cascade,
  band_id    bigint references public.band (id) on delete cascade,
  "order"    smallint not null,   -- position in the night (reserved word — quoted)
  title      text,                -- optional: "Jam abierto", "Pulse · 2º set"
  created_at timestamptz not null default now()
);
create index if not exists idx_party_set_party on public.party_set (party_id, "order");
create index if not exists idx_party_set_band on public.party_set (band_id);

create table if not exists public.performance (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  party        bigint references public.party (id),
  -- CASCADE: deleting a song erases its set-list slots everywhere, and
  -- performance_user + applause cascade under that. Cascades bypass RLS on the
  -- child tables, so the `song` DELETE policy is the only guard — see
  -- 20260909_song_moderation.sql.
  song         bigint references public.song (id) on update cascade on delete cascade,
  ref_link     varchar,
  key          varchar,             -- musical key
  "order"      smallint,            -- set-list position (reserved word — quoted)
  suggested_by uuid references public.profile (id),
  -- live mode (#37)
  live_state   public.performance_live_state not null default 'queued',
  started_at   timestamptz,         -- set on advance; opens song applause (#38)
  ended_at     timestamptz,
  -- #110: which set this song sits in. "order" therefore means position WITHIN
  -- the set, not position in the night — the night's order is party_set."order".
  -- NOT NULL since stage 2; assign_performance_set() fills it when the caller
  -- omits it, which every client path does.
  set_id       bigint not null references public.party_set (id) on delete cascade
  -- band_id added by ALTER below (band table defined later) — #40
);
create index if not exists idx_performance_set on public.performance (set_id, "order");

