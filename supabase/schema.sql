-- Every performance belongs to a set, but nobody should have to know that. This
-- assigns the trailing OPEN set (creating one when the last block is a band's)
-- whenever the caller does not name one — which is what let #110's migration
-- ship BEFORE the client that understands sets.
-- Known, self-healing race: two simultaneous first-inserts can each create an
-- open set. Two adjacent open blocks read and reorder fine and merge as soon as
-- the GC empties one; serialising it would mean locking the party per insert.
create or replace function public.assign_performance_set()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_set  bigint;
  v_band bigint;
begin
  if new.set_id is not null or new.party is null then
    return new;
  end if;
  -- The LAST BLOCK, whatever kind it is — not "the last open set anywhere".
  -- Filtering to open sets up front put a new song in the MIDDLE of the night
  -- whenever a band's block sat last, which is the shape #110 exists to create.
  select id, band_id into v_set, v_band from public.party_set
  where party_id = new.party
  order by "order" desc, id desc limit 1;
  if v_set is null or v_band is not null then
    insert into public.party_set (party_id, band_id, "order")
    select new.party, null, (coalesce(max("order"), 0) + 1)::smallint
    from public.party_set where party_id = new.party
    returning id into v_set;
  end if;
  new.set_id := v_set;
  return new;
end;
$$;
drop trigger if exists trg_assign_performance_set on public.performance;
create trigger trg_assign_performance_set
  before insert on public.performance
  for each row execute function public.assign_performance_set();

-- Only OPEN sets are collected: an empty BAND set is "Pulse is playing, we just
-- have not picked the songs yet", which an organizer placed on purpose.
create or replace function public.gc_empty_open_set()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.set_id is null then
    return null;
  end if;
  -- Fires on UPDATE OF set_id too, or an open set emptied by MOVING its last
  -- song out (routine once move_song_to_set exists) would be orphaned.
  if tg_op = 'UPDATE' and new.set_id is not distinct from old.set_id then
    return null;
  end if;
  delete from public.party_set s
  where s.id = old.set_id
    and s.band_id is null
    and not exists (select 1 from public.performance p where p.set_id = s.id);
  return null;
end;
$$;
drop trigger if exists trg_gc_empty_open_set on public.performance;
create trigger trg_gc_empty_open_set
  after delete or update of set_id on public.performance
  for each row execute function public.gc_empty_open_set();
revoke all on function public.assign_performance_set() from public, anon, authenticated;
revoke all on function public.gc_empty_open_set() from public, anon, authenticated;

