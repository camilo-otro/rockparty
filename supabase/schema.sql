-- The count without the names. NOTE it spells out party's visibility predicate
-- rather than calling can_see_party: that helper is SECURITY INVOKER by design,
-- so inside a DEFINER function it would run as the owner and answer "yes" to
-- everything, test toques included. is_dev() is DEFINER and reads auth.uid(), so
-- it is correct here. If party's SELECT policy changes, change this with it.
create or replace function public.party_rsvp_count(p_party bigint)
returns integer language sql stable security definer set search_path = '' as $$
  select case
    when exists (
      select 1 from public.party p
      where p.id = p_party and (p.is_test = false or public.is_dev())
    )
    then (select count(*)::int from public.party_rsvp r where r.party_id = p_party)
    else 0
  end;
$$;
revoke all on function public.party_rsvp_count(bigint) from public;
grant execute on function public.party_rsvp_count(bigint) to anon, authenticated;

