create extension if not exists pg_trgm;  -- for the song trigram search indexes

-- ============================ LOOKUP TABLES ==================================

create table if not exists public.role (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "roleName" varchar
);

create table if not exists public.venue_type (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null,
  description text not null
);

create table if not exists public.instrument (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name       text
);

-- ============================ CORE ENTITIES ==================================

-- profile — app users / "performers"; PK is the Supabase auth user id.
create table if not exists public.profile (
  id         uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  nickname   varchar,
  role       bigint default '3'::bigint references public.role (id),
  avatar_url text,
  email      text,
  constraint user_auth_id_key unique (id)   -- legacy unique, redundant with PK
);

-- venue — places where gigs ("toques") happen.
create table if not exists public.venue (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  name            varchar,
  address         varchar,
  contact_name    varchar,
  contact         varchar,            -- free-form handle, e.g. "@acturo"
  venue_type      bigint references public.venue_type (id),
  allow_party     boolean not null default true,
  allow_rehearsal boolean not null default false,
  created_by      uuid references public.profile (id),
  whatsapp        text,               -- added via the venue_contact branch
  instagram       text                -- added via the venue_contact branch
);

-- venue_admin — who may administer a venue (besides its creator).
-- NOTE: no primary key; created_at is timestamp WITHOUT time zone and user_id
-- is nullable — inconsistent with the other join tables. Worth tightening.
create table if not exists public.venue_admin (
  venue_id   bigint not null references public.venue (id),
  created_at timestamp default now(),
  user_id    uuid references public.profile (id)
);

-- party — a gig ("toque") at a venue on a date.
create table if not exists public.party (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  date              date,
  venue             bigint references public.venue (id),
  title             text,
  description       text,
  approved_by_venue boolean not null default false,
  created_by        uuid references public.profile (id)
);

-- party_admin — who may administer a party (besides its creator).
create table if not exists public.party_admin (
  party_id   bigint not null references public.party (id),
  created_at timestamptz not null default now(),
  user_id    uuid not null references public.profile (id),
  primary key (party_id, user_id)
);

-- song — tracks; MusicBrainz-sourced, linked to Spotify.
create table if not exists public.song (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title      varchar,
  artist     varchar,
  added_by   uuid references public.profile (id),
  duration   real default '3'::real,
  ref_link   text,
  constraint song_ref_link_key unique (ref_link),
  constraint unique_song_artist unique (title, artist)
);

create index if not exists idx_song_title_trgm  on public.song using gin (title  gin_trgm_ops);
create index if not exists idx_song_artist_trgm on public.song using gin (artist gin_trgm_ops);

-- performance — a song slotted into a party's set list (drag-orderable).
create table if not exists public.performance (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  party        bigint references public.party (id),
  song         bigint references public.song (id),
  ref_link     varchar,
  key          varchar,             -- musical key
  "order"      smallint,            -- set-list position (reserved word — quoted)
  suggested_by uuid references public.profile (id)
);

-- performance_user — a performer (user) playing an instrument in a performance.
create table if not exists public.performance_user (
  performance_id bigint not null references public.performance (id),
  created_at     timestamptz not null default now(),
  instrument_id  bigint not null references public.instrument (id),
  user_id        uuid   not null references public.profile (id),
  primary key (performance_id, instrument_id, user_id)
);

-- temp_spotify_songs — leftover import/staging table (deny-all RLS, inert).
create table if not exists public.temp_spotify_songs (
  id       bigint generated by default as identity primary key,
  title    text,
  artist   text,
  duration real,
  ref_link text
);

-- =============================================================================
-- ROW LEVEL SECURITY
-- =============================================================================
-- RLS is ENABLED on every table. General pattern:
--   * SELECT: open to anon + authenticated (public read app).
--   * INSERT: any authenticated user.
--   * UPDATE/DELETE: restricted to owners/admins via *_admin tables.
--
-- SECURITY NOTES worth reviewing (Epic 2):
--   * performance UPDATE uses `true` for authenticated — ANY logged-in user can
--     edit ANY set-list slot, not just the party's admins.
--   * performance_user UPDATE likewise `true` for authenticated.
--   * Core tables (party, venue, song, profile, performance) have NO DELETE
--     policy, so with RLS on, deletes are denied to anon/authenticated.
--   * role, temp_spotify_songs: RLS on with NO policies => fully deny-all
--     (not even SELECT). `venue_type`/`instrument` are readable; `role` is not.
-- =============================================================================

alter table public.role              enable row level security;
alter table public.venue_type        enable row level security;
alter table public.instrument        enable row level security;
alter table public.profile           enable row level security;
alter table public.venue             enable row level security;
alter table public.venue_admin       enable row level security;
alter table public.party             enable row level security;
alter table public.party_admin       enable row level security;
alter table public.song              enable row level security;
alter table public.performance       enable row level security;
alter table public.performance_user  enable row level security;
alter table public.temp_spotify_songs enable row level security;

-- ---- song -------------------------------------------------------------------
create policy "allow select to all users" on public.song
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.song
  for insert to authenticated with check (true);

-- ---- venue ------------------------------------------------------------------
create policy "allow select to all users" on public.venue
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.venue
  for insert to authenticated with check (true);
create policy "allow update to venue admins" on public.venue
  for update using (
    (created_by = auth.uid())
    or exists (
      select 1 from public.venue_admin
      where venue_admin.venue_id = venue.id and venue_admin.user_id = auth.uid()
    )
  );

-- ---- venue_admin ------------------------------------------------------------
create policy "Enable read access for all users" on public.venue_admin
  for select to anon, authenticated using (true);
create policy "allow insert for party admins" on public.venue_admin
  for insert to authenticated with check (
    ((select venue.created_by from public.venue where venue.id = venue_admin.venue_id) = auth.uid())
    or exists (
      select 1 from public.venue_admin venue_admin_1
      where venue_admin_1.venue_id = venue_admin.venue_id and venue_admin_1.user_id = auth.uid()
    )
  );
create policy "allow delete for venue admins" on public.venue_admin
  for delete to authenticated using (
    ((select auth.uid()) = user_id)
    or exists (
      select 1 from public.venue_admin venue_admin_1
      where venue_admin_1.venue_id = venue_admin.venue_id and venue_admin_1.user_id = auth.uid()
    )
  );

-- ---- party ------------------------------------------------------------------
create policy "allow select to all users" on public.party
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.party
  for insert to authenticated with check (true);
create policy "allow update to party admins" on public.party
  for update to authenticated using (
    (created_by = auth.uid())
    or exists (
      select 1 from public.party_admin
      where party_admin.party_id = party.id and party_admin.user_id = auth.uid()
    )
  ) with check (true);

-- ---- party_admin ------------------------------------------------------------
create policy "Enable read access for authenticated users" on public.party_admin
  for select to authenticated using (true);
create policy "allow Insert to party owner and other party admins" on public.party_admin
  for insert to authenticated with check (
    ((select party.created_by from public.party where party.id = party_admin.party_id) = auth.uid())
    or exists (
      select 1 from public.party_admin party_admin_1
      where party_admin_1.party_id = party_admin.party_id and party_admin_1.user_id = auth.uid()
    )
  );
create policy "Enable delete for party admins" on public.party_admin
  for delete to authenticated using (
    ((select auth.uid()) = user_id)
    or exists (
      select 1 from public.party_admin party_admin_1
      where party_admin_1.party_id = party_admin.party_id and party_admin_1.user_id = auth.uid()
    )
  );

-- ---- performance ------------------------------------------------------------
create policy "allow select to all users" on public.performance
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.performance
  for insert to authenticated with check (true);
create policy "Enable Update for authenticated users only" on public.performance
  for update to authenticated using (true) with check (true);

-- ---- performance_user -------------------------------------------------------
create policy "allow select to all users" on public.performance_user
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.performance_user
  for insert to authenticated with check (true);
create policy "Enable update for authenticated users only" on public.performance_user
  for update to authenticated using (true) with check (true);
create policy "allow delete to own user" on public.performance_user
  for delete to authenticated using (user_id = auth.uid());

-- ---- profile ----------------------------------------------------------------
create policy "allow select to all users" on public.profile
  for select to anon, authenticated using (true);
create policy "allow insert to authenticated users" on public.profile
  for insert to authenticated with check (true);
create policy "allow update to own user" on public.profile
  for update to authenticated using (id = auth.uid());

-- ---- instrument -------------------------------------------------------------
create policy "Enable read access for all users" on public.instrument
  for select to anon, authenticated using (true);

-- ---- venue_type -------------------------------------------------------------
create policy "Enable read access for all users" on public.venue_type
  for select to public using (true);

