-- MODEL NOTES
--   * There is NO `performer` table. App "performers" are `profile` rows.
--     A performer is attached to a set-list slot via `performance_user`
--     (performance x instrument x user).
--   * Admin permissions are REAL and enforced by RLS, not just hidden in the
--     UI: `venue_admin` and `party_admin` list who may edit a venue/party.
--   * `role`, `venue_type`, `instrument` are lookup tables. `profile.role`
--     and `venue.venue_type` are FKs into them (integer codes).
--   * `temp_spotify_songs` looks like a leftover import/staging table — RLS is
--     on with zero policies (deny-all), so it's inert. Candidate for removal.
