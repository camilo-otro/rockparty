-- can_see_party: party visibility used by the performance SELECT policy.
-- SECURITY INVOKER — runs as the caller and leans on party's own SELECT policy
-- for the visibility rule (single source of truth; no public security-definer
-- RPC to worry about). No recursion: party's policy doesn't reference performance.
create or replace function public.can_see_party(pid bigint)
returns boolean language sql stable security invoker set search_path = '' as $$
  select exists (select 1 from public.party p where p.id = pid);
$$;

-- can_see_band: band visibility (#76), used by the band_member / _instrument
-- SELECT policies. SECURITY INVOKER — leans on band's own SELECT policy. No
-- recursion: band's policy references only is_test and is_dev(), not band_member.
create or replace function public.can_see_band(bid bigint)
returns boolean language sql stable security invoker set search_path = '' as $$
  select exists (select 1 from public.band b where b.id = bid);
$$;

-- Who has a reason to know exactly where a venue is (#113). DEFINER because the
-- tables it reads (party, party_rsvp, performance_user) are themselves behind
-- RLS, and reading them from inside a policy evaluates as the CALLER and
-- silently under-reports. EXECUTABLE BY ANON on purpose: the policy applies
-- `to anon`, and a definer function the caller cannot execute raises
-- permission-denied instead of returning false (#102).
create or replace function public.can_see_venue_contact(vid bigint)
